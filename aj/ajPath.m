function p = ajPath(varargin)
%AJPATH  Folder of the anti-jamming campaign data (kept outside the repository).
%   p = ajPath('campaign', 'results')  ->  <base>\campaign\results
%   <base> is the environment variable AJ_DATA_ROOT or, if it is not set, the
%   parent folder of the repository. With the repository at <base>\work this is
%   the layout used for the paper:
%     <base>\data\FighterProfiles   trajectories and IMU files (generated)
%     <base>\step4\clean_single     jammer-free reference run (run_step4_tests)
%     <base>\campaign               rawIF, results, loc, noins, work (generated)
%   The IF data are generated by the code; none are stored in the repository.
base = getenv('AJ_DATA_ROOT');
if isempty(base)
    base = fileparts(fileparts(fileparts(mfilename('fullpath'))));
end
p = fullfile(base, varargin{:});
end
